# Code-derived figure data and spot checks for the technical reference.
#
#     julia --project=docs/techref/figures docs/techref/figures/generate.jl
#
# Writes TikZ data fragments and number macros to `generated/`. The LaTeX
# build only reads those committed files; it never runs Julia. Every drawn
# coordinate, ownership relation, halo weight and quoted number is read from a
# TwoPhaseAMR mesh or operator, and the assertions below fail if the
# implementation no longer matches the statements in Chapters 2 and 3.

using TwoPhaseAMR
using LinearAlgebra: Symmetric, eigmin, norm
using SparseArrays: sparse
using Printf: @sprintf

const AMR = TwoPhaseAMR
const OUTPUT = joinpath(@__DIR__, "generated")
const HEADER = "% Generated by docs/techref/figures/generate.jl; do not edit.\n"

function fmt(x::Real)
    isinteger(x) && return string(Int(x))
    text = rstrip(rstrip(@sprintf("%.6f", x), '0'), '.')
    return text == "-0" ? "0" : text
end

# Exact small fraction recovered from a floating-point value, as TeX.
function frac(x::Real)
    q = rationalize(Int, x; tol = 1.0e-12)
    @assert abs(Float64(q) - x) <= 1.0e-13 && denominator(q) <= 64
    denominator(q) == 1 && return string(numerator(q))
    sign = q < 0 ? "-" : ""
    return "$(sign)\\tfrac{$(abs(numerator(q)))}{$(denominator(q))}"
end

# A 3-root, 3-level forest: root 0 stays at level 0, root 1 is refined by the
# 2:1 balance, root 2 is refined twice. x is periodic, y has walls.
function fixture()
    return BlockTreeMesh(;
        base_mesh = (6, 2), block_size = (2, 2), extent = (12.0, 4.0),
        periodic = (true, false), max_level = 2,
        refine = (key, origin, extent) ->
            key == BlockKey(0, 2, 0) || key == BlockKey(1, 4, 1),
    )
end

function cell_box(mesh, ref::CellRef)
    block = mesh.blocks[ref.block]
    x0 = block.origin[1] + (ref.i - 1) * block.spacing[1]
    y0 = block.origin[2] + (ref.j - 1) * block.spacing[2]
    return (x0, y0, x0 + block.spacing[1], y0 + block.spacing[2])
end

function cell_at(mesh, x, y)
    for (b, block) in pairs(mesh.blocks)
        x0, y0 = block.origin
        x1, y1 = block.origin .+ block.extent
        (x0 <= x < x1 && y0 <= y < y1) || continue
        i = floor(Int, (x - x0) / block.spacing[1]) + 1
        j = floor(Int, (y - y0) / block.spacing[2]) + 1
        return CellRef(b, i, j)
    end
    error("no leaf cell contains ($x, $y)")
end

level(mesh, ref::CellRef) = mesh.blocks[ref.block].key.level
key_text(key) = "$(key.level),$(key.i),$(key.j)"

function write_output(name, text)
    path = joinpath(OUTPUT, name)
    write(path, HEADER * text)
    println("wrote ", relpath(path, @__DIR__))
    return path
end

# --- Figure: forest, leaves and levels --------------------------------------

parent_key(key) = BlockKey(key.level - 1, key.i ÷ 2, key.j ÷ 2)
child_keys(key) = [
    BlockKey(key.level + 1, 2key.i + ci, 2key.j + cj) for cj in 0:1 for ci in 0:1
]

function forest_data(mesh)
    io = IOBuffer()
    nx, ny = mesh.block_size
    println(io, "\\def\\fxBlockCellsX{$nx}\\def\\fxBlockCellsY{$ny}")
    println(io, "\\def\\fxExtentX{$(fmt(mesh.extent[1]))}\\def\\fxExtentY{$(fmt(mesh.extent[2]))}")
    # \fxleaf{array index b}{level}{i}{j}{x0}{y0}{x1}{y1}
    for (b, block) in pairs(mesh.blocks)
        key = block.key
        x0, y0 = block.origin
        x1, y1 = block.origin .+ block.extent
        println(
            io, "\\fxleaf{$b}{$(key.level)}{$(key.i)}{$(key.j)}",
            "{$(fmt(x0))}{$(fmt(y0))}{$(fmt(x1))}{$(fmt(y1))}",
        )
    end
    # Tree layout: leaves on consecutive slots, parents centred above.
    leaves = Set(block.key for block in mesh.blocks)
    nodes = Set{BlockKey}()
    for key in leaves
        node = key
        push!(nodes, node)
        while node.level > 0
            node = parent_key(node)
            push!(nodes, node)
        end
    end
    roots = sort([key for key in nodes if key.level == 0]; by = key -> (key.j, key.i))
    position = Dict{BlockKey, Float64}()
    slot = Ref(0.0)
    function place(key)
        if key in leaves
            position[key] = slot[]
            slot[] += 1
        else
            children = child_keys(key)
            all(child -> child in nodes, children) ||
                error("internal node $key without four children")
            foreach(place, children)
            position[key] = sum(position[child] for child in children) / 4
        end
        return position[key]
    end
    for root in roots
        place(root)
        slot[] += 0.6
    end
    name(key) = "n-$(key.level)-$(key.i)-$(key.j)"
    # \fxnode{name}{x}{level}{i}{j}{is leaf}
    for key in sort(collect(nodes); by = key -> (key.level, position[key]))
        println(
            io, "\\fxnode{$(name(key))}{$(fmt(position[key]))}{$(key.level)}",
            "{$(key.i)}{$(key.j)}{$(key in leaves ? 1 : 0)}",
        )
    end
    for key in sort(collect(nodes); by = key -> (key.level, position[key]))
        key.level == 0 && continue
        println(io, "\\fxedge{$(name(parent_key(key)))}{$(name(key))}")
    end
    @assert isbalanced(mesh)
    @assert length(roots) == 3
    return String(take!(io))
end

# --- Figures: hanging face, staggered unknowns, dual volumes ----------------

function interior_face(mesh, minus, plus)
    index = findfirst(f -> f.minus == minus && f.plus == plus, mesh.faces)
    isnothing(index) && error("no interior face $minus -> $plus")
    return index
end

function hanging_data(mesh)
    io = IOBuffer()
    c = cell_at(mesh, 3.0, 1.0)
    c1 = cell_at(mesh, 4.5, 0.5)
    c2 = cell_at(mesh, 4.5, 1.5)
    @assert level(mesh, c) == 0 && level(mesh, c1) == 1 && level(mesh, c2) == 1
    f1 = interior_face(mesh, c, c1)
    f2 = interior_face(mesh, c, c2)
    g = interior_face(mesh, c1, c2)
    for (label, ref) in (("c", c), ("ca", c1), ("cb", c2))
        x0, y0, x1, y1 = cell_box(mesh, ref)
        xc, yc = cellcenter(mesh, ref.block, ref.i, ref.j)
        println(
            io, "\\fxcell{$label}{$(fmt(x0))}{$(fmt(y0))}{$(fmt(x1))}{$(fmt(y1))}",
            "{$(fmt(xc))}{$(fmt(yc))}",
        )
    end
    # Context: every leaf cell in the window x < 6, with its level.
    for (b, block) in pairs(mesh.blocks), j in 1:mesh.block_size[2], i in 1:mesh.block_size[1]
        ref = CellRef(b, i, j)
        x0, y0, x1, y1 = cell_box(mesh, ref)
        x1 <= 6 || continue
        println(
            io, "\\fxcontext{$(fmt(x0))}{$(fmt(y0))}{$(fmt(x1))}{$(fmt(y1))}",
            "{$(block.key.level)}",
        )
    end
    # Every owned face of the coarse cell c with its orientation o_{c,f}.
    count = 0
    seen = Dict{NTuple{2, Float64}, Int}()
    for (index, face) in pairs(mesh.faces)
        orientation = face.minus == c ? 1 : face.plus == c ? -1 : 0
        iszero(orientation) && continue
        count += 1
        seen[face.center] = orientation
        println(
            io, "\\fxfaceofc{$(face.axis)}{$(fmt(face.center[1]))}{$(fmt(face.center[2]))}",
            "{$(fmt(face.area))}{$orientation}{0}",
        )
    end
    for face in mesh.boundary_faces
        face.cell == c || continue
        count += 1
        seen[face.center] = face.side
        println(
            io, "\\fxfaceofc{$(face.axis)}{$(fmt(face.center[1]))}{$(fmt(face.center[2]))}",
            "{$(fmt(face.area))}{$(face.side)}{1}",
        )
    end
    # f1, f2 (east, hanging), north: +1; west: -1; south wall: side -1.
    @assert seen == Dict(
        (4.0, 0.5) => 1, (4.0, 1.5) => 1, (3.0, 2.0) => 1,
        (2.0, 1.0) => -1, (3.0, 0.0) => -1,
    )
    for (label, index) in (("fa", f1), ("fb", f2), ("g", g))
        face = mesh.faces[index]
        println(
            io, "\\fxface{$label}{$(face.axis)}{$(fmt(face.center[1]))}{$(fmt(face.center[2]))}",
            "{$(fmt(face.area))}{$(fmt(mesh.face_dual_volumes[index]))}",
        )
    end
    # Staggered control volumes of every axis-1 interior face in the window:
    # half of each adjacent cell's width, times the face segment length.
    for (index, face) in pairs(mesh.faces)
        face.axis == 1 || continue
        x, y = face.center
        x0 = x - mesh.blocks[face.minus.block].spacing[1] / 2
        x1 = x + mesh.blocks[face.plus.block].spacing[1] / 2
        (x0 < 6.5 && x1 > 0) || continue
        y0, y1 = y - face.area / 2, y + face.area / 2
        @assert mesh.face_dual_volumes[index] == face.area * (x1 - x0)
        mixed = level(mesh, face.minus) != level(mesh, face.plus)
        println(
            io, "\\fxdual{$(fmt(x0))}{$(fmt(y0))}{$(fmt(x1))}{$(fmt(y1))}",
            "{$(fmt(x))}{$(fmt(mesh.face_dual_volumes[index]))}{$(mixed ? 1 : 0)}",
        )
    end
    return String(take!(io)), (; c, c1, c2, f1, f2, g, count)
end

# --- Figure: halo slots, donors and weights ---------------------------------

wrap_shift(delta, extent, periodic) = periodic ? round(delta / extent) * extent : zero(delta)

function halo_data(mesh)
    io = IOBuffer()
    b = findfirst(block -> block.key == BlockKey(1, 5, 0), mesh.blocks)
    block = mesh.blocks[b]
    x0, y0 = block.origin
    x1, y1 = block.origin .+ block.extent
    println(
        io, "\\fxhaloblock{$(fmt(x0))}{$(fmt(y0))}{$(fmt(x1))}{$(fmt(y1))}",
        "{$(fmt(block.spacing[1]))}{$(fmt(block.spacing[2]))}{$(key_text(block.key))}{$b}",
    )
    # Context cells (including the periodic image of root 0 on the right).
    window = (8.6, -1.4, 13.6, 3.4)
    for (bb, other) in pairs(mesh.blocks), j in 1:mesh.block_size[2], i in 1:mesh.block_size[1]
        cx0, cy0, cx1, cy1 = cell_box(mesh, CellRef(bb, i, j))
        for shift in (0.0, mesh.extent[1])
            sx0, sx1 = cx0 + shift, cx1 + shift
            (sx1 > window[1] && sx0 < window[3] && cy1 > window[2] && cy0 < window[4]) || continue
            println(
                io, "\\fxhalocontext{$(fmt(sx0))}{$(fmt(cy0))}{$(fmt(sx1))}{$(fmt(cy1))}",
                "{$(other.key.level)}{$(iszero(shift) ? 0 : 1)}",
            )
        end
    end
    kinds = Dict{Symbol, Int}()
    for entry in mesh.halo_entries
        entry.destination.block == b || continue
        i, j = entry.destination.i, entry.destination.j
        sx0 = x0 + (i - 1) * block.spacing[1]
        sy0 = y0 + (j - 1) * block.spacing[2]
        sx1, sy1 = sx0 + block.spacing[1], sy0 + block.spacing[2]
        first, last = entry.first_donor, entry.first_donor + entry.donor_count - 1
        donors = mesh.halo_donors[first:last]
        weights = mesh.halo_weights[first:last]
        kind = if entry.physical_boundary
            @assert length(donors) == 1 && weights[1] == 1
            :physical
        elseif length(donors) == 1 && level(mesh, donors[1]) == block.key.level
            :same
        elseif length(donors) == 1 && level(mesh, donors[1]) == block.key.level - 1
            :coarser
        elseif length(donors) == 4 && all(==(0.25), weights) &&
                all(d -> level(mesh, d) == block.key.level + 1, donors)
            :finer
        else
            error("unexpected halo entry $entry")
        end
        kinds[kind] = get(kinds, kind, 0) + 1
        @assert isapprox(sum(weights), 1; atol = 1.0e-14)
        println(
            io, "\\fxslot{$i}{$j}{$(fmt(sx0))}{$(fmt(sy0))}{$(fmt(sx1))}{$(fmt(sy1))}",
            "{$kind}{$(length(donors))}",
        )
        for (donor, weight) in zip(donors, weights)
            dx0, dy0, dx1, dy1 = cell_box(mesh, donor)
            centre = ((sx0 + sx1) / 2, (sy0 + sy1) / 2)
            shift = wrap_shift(centre[1] - (dx0 + dx1) / 2, mesh.extent[1], mesh.periodic[1])
            println(
                io, "\\fxdonor{$i}{$j}{$(fmt(dx0 + shift))}{$(fmt(dy0))}",
                "{$(fmt(dx1 + shift))}{$(fmt(dy1))}{$(fmt(weight))}{$(iszero(shift) ? 0 : 1)}",
            )
        end
    end
    @assert kinds == Dict(:physical => 4, :same => 4, :coarser => 3, :finer => 1)
    return String(take!(io)), kinds
end

# Halo weights over the whole fixture: every non-physical slot interpolates
# with weights (number of quarter-cell samples in a donor)/4 summing to one.
function halo_census(mesh)
    kinds = Dict{Symbol, Int}()
    for entry in mesh.halo_entries
        first, last = entry.first_donor, entry.first_donor + entry.donor_count - 1
        weights = mesh.halo_weights[first:last]
        @assert isapprox(sum(weights), 1; atol = 1.0e-14)
        @assert all(w -> w in (0.25, 0.5, 0.75, 1.0), weights)
        slot_level = mesh.blocks[entry.destination.block].key.level
        donor_levels = [level(mesh, d) for d in mesh.halo_donors[first:last]]
        kind = entry.physical_boundary ? :physical :
            all(==(slot_level), donor_levels) ? :same :
            all(==(slot_level - 1), donor_levels) ? :coarser :
            all(==(slot_level + 1), donor_levels) ? :finer : :mixed
        kinds[kind] = get(kinds, kind, 0) + 1
    end
    @assert !haskey(kinds, :mixed)
    return kinds
end

# --- Spot checks of Chapter 3 ------------------------------------------------

function divergence_check(mesh, faces)
    velocity = FaceVelocity(mesh)
    velocity.interior[faces.f1] = 2
    velocity.interior[faces.f2] = -1
    result = CellField(mesh)
    divergence!(result, velocity)
    values = Dict(
        :c => AMR._get(result, faces.c), :ca => AMR._get(result, faces.c1),
        :cb => AMR._get(result, faces.c2),
    )
    others = maximum(
        abs(AMR._get(result, CellRef(b, i, j)))
            for b in eachindex(mesh.blocks), j in 1:2, i in 1:2
            if CellRef(b, i, j) ∉ (faces.c, faces.c1, faces.c2)
    )
    @assert values[:c] == 0.25 && values[:ca] == -2 && values[:cb] == 1
    @assert iszero(others)
    @assert iszero(integrate(result))
    return values
end

# Open (cut-cell) divergence: the integrated contributions still cancel at a
# hanging face when apertures and open volumes are not one.
function open_divergence_check(mesh)
    # Solid disc (levelset <= 0 inside) cutting the hanging face f2 and c.
    geometry = GeometryField(mesh, (x, y) -> (x - 4.3)^2 + (y - 1.9)^2 - 0.8^2)
    velocity = FaceVelocity(mesh)
    for index in eachindex(velocity.interior)
        velocity.interior[index] = sin(1.7index) + 0.3cos(0.4index)
    end
    result = CellField(mesh)
    divergence!(result, velocity, geometry)
    total = 0.0
    scale = 0.0
    for (b, block) in pairs(mesh.blocks), j in 1:2, i in 1:2
        ref = CellRef(b, i, j)
        open_volume = AMR._get(geometry.open_fraction, ref) * block.volume
        total += open_volume * AMR._get(result, ref)
        scale += abs(open_volume * AMR._get(result, ref))
    end
    hanging = [
        index for (index, face) in pairs(mesh.faces)
            if level(mesh, face.minus) != level(mesh, face.plus) &&
            0 < geometry.aperture[index] < 1
    ]
    @assert !isempty(hanging)
    @assert abs(total) <= 1.0e-13 * scale
    return (; total, scale, cut_hanging = length(hanging))
end

function patch_faces(mesh, key)
    faces = AMR.MetricFace{Float64}[]
    for (index, face) in pairs(mesh.faces)
        any(endpoint -> AMR._vertex_key(mesh, face, endpoint) == key, 1:2) || continue
        push!(
            faces, AMR.MetricFace(
                index, face.axis, face.area, AMR._face_displacement(mesh, face),
            ),
        )
    end
    return faces
end

function hanging_vertex_metric(mesh, faces)
    face = mesh.faces[faces.f1]
    key = AMR._vertex_key(mesh, face, 2)  # upper endpoint = hanging vertex (4, 1)
    patch = patch_faces(mesh, key)
    @assert sort([f.index for f in patch]) == sort([faces.f1, faces.f2, faces.g])
    local_metric = AMR._local_inverse_metric(patch)
    order = [findfirst(f -> f.index == index, patch) for index in (faces.f1, faces.f2, faces.g)]
    K = local_metric[order, order]
    expected = [4/9 -1/9 5/18; -1/9 4/9 -5/18; 5/18 -5/18 7/9]
    @assert maximum(abs, K - expected) <= 1.0e-14
    return K, key
end

function jump_matrix(mesh)
    nx, ny = mesh.block_size
    rows = Int[]; columns = Int[]; values = Float64[]
    for (index, face) in pairs(mesh.faces)
        append!(rows, (index, index))
        append!(columns, (AMR._cell_index(face.minus, nx, ny), AMR._cell_index(face.plus, nx, ny)))
        append!(values, (-face.area, face.area))
    end
    return sparse(rows, columns, values, length(mesh.faces), ncells(mesh))
end

function metric_check(mesh)
    operator = GradientOperator(mesh)
    K = Matrix(operator.inverse_metric.matrix)
    J = jump_matrix(mesh)
    S = transpose(J) * operator.inverse_metric.matrix * J
    @assert maximum(abs, K - transpose(K)) <= 1.0e-14 * maximum(abs, K)
    smallest = eigmin(Symmetric(K))
    @assert smallest > 0
    @assert maximum(abs, S * ones(ncells(mesh))) <= 1.0e-13 * maximum(abs, S)
    offdiagonal = count(!iszero, K) - size(K, 1)
    return (; smallest, offdiagonal, faces = size(K, 1))
end

# Vertex-patch affine consistency on a wall-bounded mesh with refinement
# corners, for square (isotropic) and stretched cells.
function affine_mesh(extent)
    refined = Set([BlockKey(0, 1, 1), BlockKey(0, 2, 1), BlockKey(0, 1, 2), BlockKey(1, 3, 3)])
    return BlockTreeMesh(;
        base_mesh = (8, 8), block_size = (2, 2), extent, periodic = (false, false),
        max_level = 2, refine = (key, origin, extent) -> key in refined,
    )
end

function affine_check(mesh)
    patches_by_vertex = Dict{Tuple{Int, Int}, Vector{Int}}()
    for (index, face) in pairs(mesh.faces), endpoint in 1:2
        push!(get!(patches_by_vertex, AMR._vertex_key(mesh, face, endpoint), Int[]), index)
    end
    complete(key) = !AMR._physical_vertex(mesh, key) && length(patches_by_vertex[key]) >= 3
    asymmetric = 0
    residual_symmetric = 0.0
    residual_asymmetric = 0.0
    patches = 0
    for key in keys(patches_by_vertex)
        complete(key) || continue
        patches += 1
        faces = patch_faces(mesh, key)
        Y = [f.area * f.displacement[k] for f in faces, k in 1:2]
        N = [f.axis == k ? 0.5 : 0.0 for f in faces, k in 1:2]
        YN = transpose(Y) * N
        residual = maximum(abs, AMR._local_inverse_metric(faces) * Y - N)
        if abs(YN[1, 2] - YN[2, 1]) > 1.0e-12 * maximum(abs, YN)
            asymmetric += 1
            residual_asymmetric = max(residual_asymmetric, residual)
        else
            residual_symmetric = max(residual_symmetric, residual)
        end
    end
    pressure = CellField(mesh, (x, y) -> 0.3x - 0.7y)
    gradient = FaceVelocity(mesh)
    gradient!(gradient, pressure, GradientOperator(pressure))
    error_complete = 0.0
    for (index, face) in pairs(mesh.faces)
        all(endpoint -> complete(AMR._vertex_key(mesh, face, endpoint)), 1:2) || continue
        exact = face.axis == 1 ? 0.3 : -0.7
        error_complete = max(error_complete, abs(gradient.interior[index] - exact))
    end
    return (; patches, asymmetric, residual_symmetric, residual_asymmetric, error_complete)
end

macro_line(name, value) = "\\newcommand\\$name{$value}\n"

function main()
    mkpath(OUTPUT)
    mesh = fixture()
    write_output("forest.tex", forest_data(mesh))
    hanging, faces = hanging_data(mesh)
    write_output("hanging.tex", hanging)
    halo, halo_kinds = halo_data(mesh)
    write_output("halo.tex", halo)
    census = halo_census(mesh)
    divergence = divergence_check(mesh, faces)
    open = open_divergence_check(mesh)
    K, _ = hanging_vertex_metric(mesh, faces)
    metric = metric_check(mesh)
    square = affine_check(affine_mesh((1.0, 1.0)))
    stretched = affine_check(affine_mesh((2.0, 1.0)))
    @assert square.asymmetric == 0 && square.residual_symmetric <= 1.0e-13
    @assert square.error_complete <= 1.0e-12
    @assert stretched.asymmetric > 0 && stretched.residual_asymmetric > 1.0e-3

    sci(x) = iszero(x) ? "0" : begin
        exponent = floor(Int, log10(abs(x)))
        @sprintf("%.1f\\times10^{%d}", x / 10.0^exponent, exponent)
    end
    checks = IOBuffer()
    print(checks, macro_line("chkBlocks", length(mesh.blocks)))
    print(checks, macro_line("chkCells", ncells(mesh)))
    print(checks, macro_line("chkInteriorFaces", length(mesh.faces)))
    print(checks, macro_line("chkBoundaryFaces", length(mesh.boundary_faces)))
    print(checks, macro_line("chkFacesOfC", faces.count))
    print(checks, macro_line("chkDualCoarseFine", fmt(mesh.face_dual_volumes[faces.f1])))
    print(checks, macro_line("chkDivC", fmt(divergence[:c])))
    print(checks, macro_line("chkDivCa", fmt(divergence[:ca])))
    print(checks, macro_line("chkDivCb", fmt(divergence[:cb])))
    print(checks, macro_line("chkOpenDivSum", sci(abs(open.total))))
    print(checks, macro_line("chkOpenDivScale", sci(open.scale)))
    print(checks, macro_line("chkOpenCutHanging", open.cut_hanging))
    for (name, value) in (
            ("chkKaa", K[1, 1]), ("chkKab", K[1, 2]), ("chkKag", K[1, 3]),
            ("chkKbb", K[2, 2]), ("chkKbg", K[2, 3]), ("chkKgg", K[3, 3]),
        )
        print(checks, macro_line(name, frac(value)))
    end
    print(checks, macro_line("chkMetricFaces", metric.faces))
    print(checks, macro_line("chkMetricOffdiag", metric.offdiagonal))
    print(checks, macro_line("chkMetricEigmin", sci(metric.smallest)))
    for (prefix, result) in (("Square", square), ("Stretched", stretched))
        print(checks, macro_line("chk$(prefix)Patches", result.patches))
        print(checks, macro_line("chk$(prefix)Asymmetric", result.asymmetric))
        print(checks, macro_line("chk$(prefix)ResidualSym", sci(result.residual_symmetric)))
        print(checks, macro_line("chk$(prefix)ResidualAsym", sci(result.residual_asymmetric)))
        print(checks, macro_line("chk$(prefix)AffineError", sci(result.error_complete)))
    end
    for kind in (:same, :coarser, :finer, :physical)
        print(checks, macro_line("chkHalo$(uppercasefirst(String(kind)))", get(census, kind, 0)))
    end
    write_output("checks.tex", String(take!(checks)))

    println("halo kinds of block (1,5,0): ", halo_kinds)
    println("halo census of fixture:      ", census)
    println("divergence spot check:       ", divergence)
    println("open divergence:             ", open)
    println("hanging-vertex K^v:          ", K)
